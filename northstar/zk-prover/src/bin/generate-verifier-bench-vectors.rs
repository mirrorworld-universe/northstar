use {
    ark_bn254::{Bn254, Fr},
    ark_groth16::Groth16,
    ark_relations::r1cs::ConstraintSynthesizer,
    ark_std::rand::SeedableRng,
    northstar_zk_prover::{
        proof_to_solana, sample_circuit, verifying_key_to_solana, Groth16VerifyingKeyRaw,
        PaddedPublicInputCircuitV1,
    },
    rand_chacha::ChaCha20Rng,
    serde_json::json,
    std::{
        env,
        fmt::Write,
        fs,
        path::{Path, PathBuf},
    },
};

fn bytes_hex(bytes: impl AsRef<[u8]>) -> String {
    format!("0x{}", hex::encode(bytes))
}

fn rust_bytes(bytes: &[u8], indent: &str) -> String {
    let mut output = String::from("[\n");
    for chunk in bytes.chunks(16) {
        output.push_str(indent);
        for byte in chunk {
            write!(output, "0x{byte:02x}, ").unwrap();
        }
        output.push('\n');
    }
    output.push_str(indent.strip_suffix("    ").unwrap_or(indent));
    output.push(']');
    output
}

fn render_key(name: &str, key: &Groth16VerifyingKeyRaw) -> String {
    let mut output = format!("const {name}_IC: [[u8; 64]; {}] = [\n", key.ic.len());
    for point in &key.ic {
        writeln!(output, "    {},", rust_bytes(point, "        ")).unwrap();
    }
    writeln!(output, "];\n").unwrap();
    writeln!(
        output,
        "pub const {name}: Groth16Verifyingkey<'static> = Groth16Verifyingkey {{"
    )
    .unwrap();
    let public_inputs = key
        .ic
        .len()
        .checked_sub(1)
        .expect("verifying key contains the constant term");
    writeln!(output, "    nr_pubinputs: {public_inputs},").unwrap();
    writeln!(
        output,
        "    vk_alpha_g1: {},",
        rust_bytes(&key.alpha_g1, "        ")
    )
    .unwrap();
    writeln!(
        output,
        "    vk_beta_g2: {},",
        rust_bytes(&key.beta_g2, "        ")
    )
    .unwrap();
    writeln!(
        output,
        "    vk_gamma_g2: {},",
        rust_bytes(&key.gamma_g2, "        ")
    )
    .unwrap();
    writeln!(
        output,
        "    vk_delta_g2: {},",
        rust_bytes(&key.delta_g2, "        ")
    )
    .unwrap();
    writeln!(output, "    vk_ic: &{name}_IC,").unwrap();
    writeln!(output, "    vk_commitment: None,\n}};\n").unwrap();
    output
}

fn generate<const N: usize>(
    output_dir: &Path,
    source: &mut String,
    seed: u8,
) -> Groth16VerifyingKeyRaw {
    let transition = sample_circuit().unwrap();
    let circuit = PaddedPublicInputCircuitV1::<N> {
        transition: transition.clone(),
    };
    let mut setup_rng = ChaCha20Rng::from_seed([seed; 32]);
    let proving_key = Groth16::<Bn254>::generate_random_parameters_with_reduction(
        circuit.clone(),
        &mut setup_rng,
    )
    .unwrap();
    let proof_seed = seed
        .checked_add(32)
        .expect("fixture seed does not overflow");
    let mut proof_rng = ChaCha20Rng::from_seed([proof_seed; 32]);
    let proof =
        Groth16::<Bn254>::create_random_proof_with_reduction(circuit, &proving_key, &mut proof_rng)
            .unwrap();
    let proof = proof_to_solana(&proof).unwrap();
    let key = verifying_key_to_solana(&proving_key.vk).unwrap();
    let mut public_inputs: Vec<[u8; 32]> = transition.public.to_array().into_iter().collect();
    public_inputs.resize(N, [0; 32]);

    let cs = ark_relations::r1cs::ConstraintSystem::<Fr>::new_ref();
    PaddedPublicInputCircuitV1::<N> { transition }
        .generate_constraints(cs.clone())
        .unwrap();
    cs.finalize();
    let vector = json!({
        "schema": "northstar-groth16-verifier-benchmark-v1",
        "public_input_count": N,
        "constraints": cs.num_constraints(),
        "deterministic_test_only": true,
        "public_inputs_be": public_inputs.iter().map(bytes_hex).collect::<Vec<_>>(),
        "proof_be": {
            "a": bytes_hex(proof.a),
            "b": bytes_hex(proof.b),
            "c": bytes_hex(proof.c)
        }
    });
    fs::write(
        output_dir.join(format!("groth16-{N}-inputs.json")),
        format!("{}\n", serde_json::to_string_pretty(&vector).unwrap()),
    )
    .unwrap();
    source.push_str(&render_key(&format!("VERIFYING_KEY_{N}"), &key));
    key
}

fn main() {
    let repository = env::args_os()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("."));
    let output_dir = repository.join("northstar/zk-verifier-bench/vectors");
    fs::create_dir_all(&output_dir).unwrap();
    let mut source = String::from(
        "// Generated by `northstar-zk-prover --bin generate-verifier-bench-vectors`.\n// \
         Deterministic benchmark keys only; never use for production funds.\n\nuse \
         groth16_solana::groth16::Groth16Verifyingkey;\n\n",
    );
    generate::<8>(&output_dir, &mut source, 8);
    generate::<12>(&output_dir, &mut source, 12);
    generate::<16>(&output_dir, &mut source, 16);
    let key_path = repository.join("northstar/zk-verifier-bench/src/verifying_keys.rs");
    fs::create_dir_all(key_path.parent().unwrap()).unwrap();
    fs::write(&key_path, source).unwrap();
    println!("wrote {}", output_dir.display());
    println!("wrote {}", key_path.display());
}
